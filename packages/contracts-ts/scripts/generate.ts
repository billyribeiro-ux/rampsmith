/**
 * Generates TypeScript declarations from the JSON Schemas written by `gen-schemas`.
 *
 * Usage: node scripts/generate.ts <schemas-dir> <output-dir>
 *
 * The output directory is replaced wholesale, so a removed schema removes its types too.
 * Output is deterministic; CI generates into a temporary directory and diffs (PLAN §24).
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';
import { compile, type JSONSchema } from 'json-schema-to-typescript';

const BANNER =
  '/* Generated by packages/contracts-ts/scripts/generate.ts from crates/contracts. Do not edit. */';

const [schemasDir, outDir] = process.argv.slice(2);
if (schemasDir === undefined || outDir === undefined) {
  throw new Error('usage: node scripts/generate.ts <schemas-dir> <output-dir>');
}

const SUFFIX = '.schema.json';
const names = readdirSync(schemasDir)
  .filter((file) => file.endsWith(SUFFIX))
  .map((file) => file.slice(0, -SUFFIX.length))
  .sort();

// Replace this script's own files; leave api.ts, written by generate-api.ts, alone.
mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(outDir)) {
  if (file !== 'api.ts') rmSync(join(outDir, file));
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Gives every `$defs` entry a title, so each becomes a named, importable type. */
function nameDefinitions(schema: JSONSchema): JSONSchema {
  const defs: unknown = schema['$defs'];
  if (!isRecord(defs)) {
    return schema;
  }
  const named: Record<string, unknown> = {};
  for (const [key, def] of Object.entries(defs)) {
    named[key] = isRecord(def) && typeof def['title'] !== 'string' ? { ...def, title: key } : def;
  }
  return { ...schema, $defs: named };
}

for (const name of names) {
  const parsed = JSON.parse(
    readFileSync(join(schemasDir, `${name}${SUFFIX}`), 'utf8'),
  ) as JSONSchema;
  const schema = nameDefinitions(parsed);
  const source = await compile(schema, name, {
    bannerComment: BANNER,
    strictIndexSignatures: true,
    style: { singleQuote: true, printWidth: 100, trailingComma: 'all' },
  });
  writeFileSync(join(outDir, `${name}.ts`), source);
}

const index = names.map((name) => `export type * from './${name}.ts';`).join('\n');
writeFileSync(join(outDir, 'index.ts'), `${BANNER}\n${index}\n`);
